"""PersistenceStack — the RETAIN'd state.

Aurora Serverless v2 (the event log + projections) and the per-run capability signing secret. Both
are state whose loss invalidates in-flight runs, so they are isolated in a stack that nothing
downstream ever modifies on deploy, away from the churning CloudFront distribution and UI bucket.

Consumers (the ingest, reconcile, and backend Lambdas) reference the exposed L2 objects (the
cluster and its credentials secret) and grant themselves from their own side (`wiring.wire_db`,
`wiring.grant_secret_read`), so the security-group ingress rule and the key grants land in the
CONSUMER's stack and this stack stays a pure source.
"""

from __future__ import annotations

from typing import Any

from aws_cdk import Duration, RemovalPolicy, Stack
from aws_cdk import aws_ec2 as ec2
from aws_cdk import aws_rds as rds
from aws_cdk import aws_secretsmanager as secretsmanager
from constructs import Construct

from biffix_infra.config import DeployConfig
from biffix_infra.constructs.encrypted_bucket import customer_key


class PersistenceStack(Stack):
    def __init__(
        self, scope: Construct, cid: str, *, vpc: ec2.IVpc, config: DeployConfig, **kwargs: Any
    ) -> None:
        super().__init__(scope, cid, **kwargs)

        # The event log is the store most likely to hold regulated data (run parameters, sample
        # names, submitters), so it and its secrets are encrypted with a customer-managed key, the
        # deployer's own with `aurora_key_arn`, never the AWS-managed aws/rds and
        # aws/secretsmanager keys. The secrets' readers get decrypt on it with their read grant.
        self.key = customer_key(self, "EventStoreKey", config.aurora_key_arn)

        # The cluster's master credentials, made here rather than generated by the cluster so that
        # consumers can import the secret's own ARN. `db.secret` is the cluster's
        # SecretTargetAttachment, whose Ref changes whenever the cluster is replaced, and
        # CloudFormation refuses to change an export another stack imports: a replacement would
        # fail on the export lock. The secret's ARN survives a cluster replacement. RETAINed like
        # the cluster it unlocks.
        self.db_secret = rds.DatabaseSecret(
            self, "EventStoreSecret", username="postgres", encryption_key=self.key
        )
        self.db_secret.apply_removal_policy(RemovalPolicy.RETAIN)

        # Aurora Serverless v2 (Postgres) — the event-sourced system of record.
        self.db = rds.DatabaseCluster(
            self,
            "EventStore",
            engine=rds.DatabaseClusterEngine.aurora_postgres(
                version=rds.AuroraPostgresEngineVersion.VER_16_9
            ),
            vpc=vpc,
            vpc_subnets=ec2.SubnetSelection(subnet_type=ec2.SubnetType.PRIVATE_WITH_EGRESS),
            # Scale to zero when idle (~$0). Cold-start after idle adds a ~15s resume on the first
            # request; active runs keep it warm (ingest writes on every Batch event), and /readyz
            # (open, SELECT 1) is the warm hook if we later add a business-hours ping.
            serverless_v2_min_capacity=0,
            serverless_v2_max_capacity=8,
            writer=rds.ClusterInstance.serverless_v2("writer"),
            credentials=rds.Credentials.from_secret(self.db_secret),
            storage_encrypted=True,
            storage_encryption_key=self.key,
            removal_policy=RemovalPolicy.RETAIN,
            # Backup depth for the system of record is chosen explicitly, not left at the RDS
            # default. Automated backups within this window also define the point-in-time
            # recovery horizon. deletion_protection is a second, independent guard from
            # RemovalPolicy.RETAIN (which only governs stack-teardown behaviour): it blocks a
            # cluster delete from ANY path, so a deliberate teardown must clear it first — the same
            # posture as this stack's termination protection.
            backup=rds.BackupProps(retention=Duration.days(config.aurora_backup_retention_days)),
            deletion_protection=True,
        )

        # The capability-token signing key. The coordinator authenticates to
        # POST /events with a per-run HMAC token the backend both mints (at submit) and verifies (at
        # ingest), so exactly ONE component needs the key and it never appears in the template or in
        # a Lambda env var — only its ARN does. RETAINed: replacing it would silently invalidate the
        # tokens of runs still executing. It lives here (not in the api stack) because it is
        # run-invalidating state, the same class as the database.
        self.capability_secret = secretsmanager.Secret(
            self,
            "CapabilitySigningKey",
            description="biffix per-run ingest capability token signing key (HMAC-SHA256)",
            encryption_key=self.key,
            generate_secret_string=secretsmanager.SecretStringGenerator(
                password_length=64,
                exclude_punctuation=True,
            ),
            removal_policy=RemovalPolicy.RETAIN,
        )
