//! The Dockerfile biffix builds a pixi environment's image with (`images.<name>: {pixi: <dir>}`).
//!
//! The environment is installed from its lock file alone (`pixi install --locked`, so a
//! `pixi.toml` edited without re-locking fails the build instead of resolving anew) in pixi's own
//! image, then copied into a plain Ubuntu base. The image's entrypoint activates the environment
//! before the task's command. It carries no AWS CLI (the host supplies it) and no Snakemake (a
//! Snakemake image gets the version's runtime added afterwards, like any other image).
//!
//! The text is a pure function of `PIXI_GENERATOR_VERSION` and the pins below, and every pixi
//! image's key ([`crate::images::build_content_key`]) hashes the text itself: changing a pin, the
//! template or the version rebuilds every pixi image rather than silently reusing one.

/// Bumped whenever [`dockerfile`]'s output changes (the build key hashes the text too, so a
/// forgotten bump still rebuilds; the version says which generator an image came from).
pub(crate) const PIXI_GENERATOR_VERSION: u32 = 1;

/// The image pixi installs the environment in (multi-arch index, pinned by digest).
pub(crate) const PIXI_IMAGE: &str = "ghcr.io/prefix-dev/pixi:0.71.0@sha256:865b0a15b0f89ff2ce095f0719ee758208a26b38c7426c47748a0fd0cf602c4d";

/// The base the environment is copied into (multi-arch index, pinned by digest).
pub(crate) const PIXI_BASE_IMAGE: &str = "public.ecr.aws/ubuntu/ubuntu:24.04@sha256:f4da486bc9b357039b00eb68d03fdbda5570525a5c14f56907d75fd5aa204f8f";

/// The files of a pixi environment's directory that make up its build context.
pub const PIXI_FILES: [&str; 2] = ["pixi.toml", "pixi.lock"];

/// Where the environment lives in the image.
pub(crate) const PIXI_APP_DIR: &str = "/app";

/// The generated Dockerfile (its context is the environment's [`PIXI_FILES`]).
pub fn dockerfile() -> String {
    format!(
        r#"# Generated by biffix (pixi generator {PIXI_GENERATOR_VERSION}).
FROM {PIXI_IMAGE} AS pixi
WORKDIR {PIXI_APP_DIR}
COPY pixi.toml pixi.lock ./
RUN pixi install --locked -e default && pixi shell-hook -e default > {PIXI_APP_DIR}/env.sh

FROM {PIXI_BASE_IMAGE}
COPY --from=pixi {PIXI_APP_DIR} {PIXI_APP_DIR}
ENV PATH={PIXI_APP_DIR}/.pixi/envs/default/bin:$PATH
ENTRYPOINT ["/bin/bash", "-c", "source {PIXI_APP_DIR}/env.sh && exec \"$@\"", "--"]
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_generated_dockerfile_is_pinned_and_activates_the_environment() {
        let text = dockerfile();
        assert_eq!(
            text,
            format!(
                "# Generated by biffix (pixi generator 1).\n\
                 FROM {PIXI_IMAGE} AS pixi\n\
                 WORKDIR /app\n\
                 COPY pixi.toml pixi.lock ./\n\
                 RUN pixi install --locked -e default && pixi shell-hook -e default > /app/env.sh\n\
                 \n\
                 FROM {PIXI_BASE_IMAGE}\n\
                 COPY --from=pixi /app /app\n\
                 ENV PATH=/app/.pixi/envs/default/bin:$PATH\n\
                 ENTRYPOINT [\"/bin/bash\", \"-c\", \"source /app/env.sh && exec \\\"$@\\\"\", \"--\"]\n"
            )
        );
        // Every base is pinned by digest, and nothing adds an AWS CLI or Snakemake.
        for image in [PIXI_IMAGE, PIXI_BASE_IMAGE] {
            assert!(image.contains("@sha256:"), "{image}");
        }
        assert!(
            !text.contains("awscli") && !text.contains("aws-cli") && !text.contains("snakemake")
        );
    }
}
