import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const uiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(uiRoot, '..');
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'biffix-openapi-'));
const documentPath = join(temporaryDirectory, 'openapi.json');
const outputPath = join(uiRoot, 'src', 'lib', 'generated', 'api.ts');
mkdirSync(dirname(outputPath), { recursive: true });
const openapiExecutable = join(
  uiRoot,
  'node_modules',
  '.bin',
  process.platform === 'win32' ? 'openapi-typescript.cmd' : 'openapi-typescript',
);
const prettierExecutable = join(
  uiRoot,
  'node_modules',
  '.bin',
  process.platform === 'win32' ? 'prettier.cmd' : 'prettier',
);

try {
  const document = execFileSync(
    'cargo',
    [
      'run',
      '--locked',
      '--quiet',
      '--manifest-path',
      join(repoRoot, 'Cargo.toml'),
      '-p',
      'biffix-backend',
      '--bin',
      'biffix-openapi',
    ],
    // The document is printed whole to stdout: room well past its size (Node's default is 1 MiB).
    { cwd: repoRoot, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  writeFileSync(documentPath, document);
  // Also emit the raw spec as an importable asset for the in-app API docs page (Swagger UI).
  const specPath = join(uiRoot, 'src', 'lib', 'generated', 'openapi.json');
  writeFileSync(specPath, document);
  execFileSync(openapiExecutable, [documentPath, '--output', outputPath], {
    cwd: uiRoot,
    stdio: 'inherit',
  });

  const generated = readFileSync(outputPath, 'utf8');
  writeFileSync(
    outputPath,
    `// Generated from the Rust backend's utoipa document by npm run generate:api.\n` +
      `// Do not edit this file by hand.\n${generated}`,
  );
  execFileSync(prettierExecutable, ['--write', outputPath], {
    cwd: uiRoot,
    stdio: 'inherit',
  });

  // Types with a schemars schema only (FormSchema, the sample-detection contract, a run's sample
  // progress). The Rust structs are the single source of truth; schemars emits
  // schemas/*.schema.json from them (drift-gated by `cargo xtask emit-schemas --check`), and the TS
  // is generated from those JSON schemas. So these UI types are a generated projection of the Rust
  // structs, never a hand-kept mirror that can drift.
  for (const [schema, output] of [
    ['formschema.schema.json', 'formschema.ts'],
    // The sample-detection endpoint's request/response (biffix_api::SamplesContract).
    ['samples.schema.json', 'samples.ts'],
    // A run's samples × steps (biffix_core::sample_progress).
    ['sample-progress.schema.json', 'sample-progress.ts'],
  ]) {
    const schemaPath = join(repoRoot, 'schemas', schema);
    const typesPath = join(uiRoot, 'src', 'lib', 'generated', output);
    const types = await compileFromFile(schemaPath, {
      bannerComment: '',
      additionalProperties: false,
      format: false,
      cwd: dirname(schemaPath),
    });
    writeFileSync(
      typesPath,
      `// Generated from schemas/${schema} by npm run generate:api.\n` +
        `// Do not edit this file by hand.\n${types}`,
    );
    execFileSync(prettierExecutable, ['--write', typesPath], {
      cwd: uiRoot,
      stdio: 'inherit',
    });
  }
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
